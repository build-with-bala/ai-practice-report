import { afterEach, beforeEach, describe, expect, test } from "bun:test";
import { classifyCommit, LOG_FORMAT, parseLog, shaKey } from "../../../core/git/commits";
import { scan } from "../../../core/scan";
import { ccTranscripts } from "../../../core/sources/claude-code";
import { keyedHash } from "../../../core/text/hash";
import { CcTranscript, ccSid, slug } from "../../fixtures/claude-code";
import { fakeHome, type FakeHome } from "../../kit/home";

const salt = new Uint8Array(32).fill(7);
const SHA1 = "abc1234def5678901234567890abcdef12345678";
const SHA2 = "0123456789abcdef0123456789abcdef01234567";
const SHA3 = "fedcba9876543210fedcba9876543210fedcba98";

/** One record as `git log` prints LOG_FORMAT with `--name-only`. */
const rec = (sha: string, ct: number, email: string, body: string, files: string[] = []) =>
  `\x1e${sha}\x1f${ct}\x1f${email}\x1f${body}\x1f${files.length ? `\n\n${files.join("\n")}\n` : "\n"}`;

describe("classifyCommit", () => {
  const cases: [string, ReturnType<typeof classifyCommit>][] = [
    ["feat: x\n\nCo-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>", { ai: "claude" }],
    ["feat: x\n\n🤖 Generated with [Claude Code](https://claude.com/claude-code)", { generated: "claude" }],
    ['Revert "feat: x"\n\nThis reverts commit abc.', { rework: "revert" }],
    ["fixup! feat", { rework: "fixup" }],
    ["squash! feat", { rework: "fixup" }],
    ["fix(api): y", { rework: "fix" }],
    ["hotfix!: y", { rework: "fix" }],
    ["Co-authored-by: Jane <jane@x.test>", {}],
    ["feat: a\n\nCo-authored-by: Jane <jane@x.test>\nCo-authored-by: Copilot <copilot@users.noreply.github.com>", { ai: "copilot" }],
    ["feat\n\nco-authored-by: chatgpt-codex-connector[bot] <x@users.noreply.github.com>", { ai: "codex" }],
    ["feat\n\nCo-authored-by: Cursor Agent <cursoragent@cursor.com>", { ai: "cursor" }],
    ["feat\n\nCo-authored-by: google-labs-jules[bot] <x@y.test>", { ai: "gemini" }],
    ["feat\n\nCo-authored-by: aider (gpt) <noreply@aider.chat>", { ai: "aider" }],
    ["feat\n\nCo-authored-by: Amp <amp@ampcode.com>", { ai: "other" }],
    // whole words only: a person whose name holds a tool's letters is no AI
    ["feat\n\nCo-authored-by: Sam Ampleford <sam@x.test>\nCo-authored-by: Android Dev <a@x.test>", {}],
    ["Fix a bug", {}],
    ["feat: fix: not the subject's start", {}],
    ["docs\n\nGenerated by Gemini CLI", { generated: "gemini" }],
  ];
  for (const [message, want] of cases) test(JSON.stringify(message.slice(0, 40)), () => expect(classifyCommit(message)).toEqual(want));
});

describe("parseLog", () => {
  test("the format asks for sha, commit time, author email and message, each record and field delimited", () => {
    expect(LOG_FORMAT).toBe("--format=%x1e%H%x1f%ct%x1f%ae%x1f%B%x1f");
  });

  test("only the given email's commits (case-insensitively), as keyed facts; 200 of 250 paths kept", () => {
    const many = Array.from({ length: 250 }, (_, i) => `src/f${i}.ts`);
    const out = rec(SHA1, 1_700_000_000, "Me@X.test", "feat: a\n\nCo-authored-by: Claude <noreply@anthropic.com>\n", ["src/a.ts", "dir with space/ünï.ts"])
      + rec(SHA2, 1_700_000_100, "someone@else.test", "feat: theirs\n", ["src/b.ts"])
      + rec(SHA3, 1_700_000_200, "me@x.test", "fix: b\n", many);
    const facts = parseLog(out, { salt, email: "me@x.test", maxFiles: 200 });
    expect(facts).toHaveLength(2);
    expect(facts[0]).toEqual({ ts: 1_700_000_000_000, shaKey: keyedHash(salt, "abc1234"), ai: "claude", files: [keyedHash(salt, "src/a.ts"), keyedHash(salt, "dir with space/ünï.ts")] });
    expect(facts[1]!.rework).toBe("fix");
    expect(facts[1]!.files).toHaveLength(200);
    for (const f of facts.flatMap((c) => c.files)) expect(f).toMatch(/^[0-9a-f]{16}$/);
    expect(JSON.stringify(facts)).not.toContain("src/");
  });

  test("a commit is keyed by its sha's first 7 hex digits, lower-cased", () => {
    const facts = parseLog(rec(SHA1.toUpperCase(), 1, "me@x.test", "x\n"), { salt, email: "me@x.test", maxFiles: 200 });
    expect(facts[0]!.shaKey).toBe(keyedHash(salt, "abc1234"));
    expect(shaKey(salt, "ABC1234DEF")).toBe(keyedHash(salt, "abc1234"));
  });

  test("a record cut short, and one without a sha, are left out; without --name-only a commit lists no files", () => {
    const out = rec(SHA1, 1, "me@x.test", "x\n") + "\x1enot-a-sha\x1f1\x1fme@x.test\x1fy\x1f\n" + `\x1e${SHA2}\x1f2\x1fme@x`;
    expect(parseLog(out, { salt, email: "me@x.test", maxFiles: 200 }).map((c) => c.files)).toEqual([[]]);
  });
});

describe("one commit, one key: git and Claude Code agree (shared vector)", () => {
  let h: FakeHome;
  beforeEach(() => { h = fakeHome(); });
  afterEach(() => h.cleanup());

  test("a git %H starting ABC1234 and a Claude Code sha ABC1234def both key as keyedHash(salt, \"abc1234\")", async () => {
    const want = keyedHash(salt, "abc1234");
    // the Claude Code side: a commit marker read from a transcript
    const t = new CcTranscript(ccSid("SV1")).prompt("commit it").tool("toolu_sv1", "Bash", { command: "git commit -m x" }, {
      content: "[main ABC1234] x", toolUseResult: { stdout: "", stderr: "", interrupted: false, gitOperation: { commit: { sha: "ABC1234def", kind: "commit", branch: "main" } } },
    });
    t.write(h, `.claude/projects/${slug("/work/p")}/${ccSid("SV1")}.jsonl`);
    const r = await scan({ env: h.env, plugins: [ccTranscripts], salt, repoSignals: false });
    const marker = r.store.all("marker").find((m) => m.kind === "commit");
    // the git side: the same commit in `git log` output, its sha in any case
    const [lower] = parseLog(rec("abc1234def5678901234567890abcdef12345678", 1, "me@x.test", "x\n"), { salt, email: "me@x.test", maxFiles: 200 });
    const [upper] = parseLog(rec("ABC1234DEF5678901234567890ABCDEF12345678", 1, "me@x.test", "x\n"), { salt, email: "me@x.test", maxFiles: 200 });
    expect([marker?.detail, lower!.shaKey, upper!.shaKey]).toEqual([want, want, want]);
  });
});
