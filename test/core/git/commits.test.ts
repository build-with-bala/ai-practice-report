describe("parseLog", () => {
  test("the format asks for sha, commit time, author email and message; records end with NUL (-z)", () => {
    expect(LOG_ARGS).toEqual(["-z", "--format=%x00%x1e%H%x1f%ct%x1f%ae%x1f%B"]);
  });

  test("a \\x1e (or \\x1f) inside a message neither drops the real commit nor forges a record", () => {
    const forged = `\x1e${SHA2}\x1f1\x1fme@x.test\x1fforged`;
    const out = rec(SHA1, 1, "me@x.test", `feat: a ${forged}\x1f tail\n`, ["a.ts"]) + rec(SHA3, 2, "me@x.test", "b\n");
    const records = logRecords(out);
    expect(records.map((r) => [r.sha, r.files])).toEqual([[SHA1, ["a.ts"]], [SHA3, []]]);
    expect(records[0]!.message).toBe(`feat: a ${forged}\x1f tail\n`);
    expect(parseLog(out, { salt, email: "me@x.test", maxFiles: 200 }).map((c) => c.shaKey)).toEqual([keyedHash(salt, "abc1234"), keyedHash(salt, "fedcba9")]);
  });

  test("a changed path shaped like a record is a path, never a record", () => {
    const hostile = `\x1e${"d".repeat(40)}\x1f1700000001\x1fme@x.test\x1fCo-authored-by: Claude <noreply@anthropic.com>`;
    const out = rec(SHA1, 1, "me@x.test", "x\n", ["a.ts", hostile, hostile]) + rec(SHA3, 2, "me@x.test", "y\n", [hostile]);
    expect(logRecords(out).map((r) => [r.sha, r.files.length])).toEqual([[SHA1, 3], [SHA3, 1]]);
    expect(parseLog(out, { salt, email: "me@x.test", maxFiles: 200 }).map((c) => c.ai)).toEqual([undefined, undefined]);
  });

  test("only the given email's commits (case-insensitively), as keyed facts; 200 of 250 paths kept", () => {
    const many = Array.from({ length: 250 }, (_, i) => `src/f${i}.ts`);
    const out = rec(SHA1, 1_700_000_000, "Me@X.test", "feat: a\n\nCo-authored-by: Claude <noreply@anthropic.com>\n", ["src/a.ts", "dir with space/ünï.ts"])
      + rec(SHA2, 1_700_000_100, "someone@else.test", "feat: theirs\n", ["src/b.ts"])
      + rec(SHA3, 1_700_000_200, "me@x.test", "fix: b\n", many);
    const facts = parseLog(out, { salt, email: "me@x.test", maxFiles: 200 });
    expect(facts).toHaveLength(2);
    expect(facts[0]).toEqual({ ts: 1_700_000_000_000, shaKey: keyedHash(salt, "abc1234"), ai: "claude", files: [keyedHash(salt, "src/a.ts"), keyedHash(salt, "dir with space/ünï.ts")], owner: true });
    expect(facts[1]!.rework).toBe("fix");
    expect(facts[1]!.files).toHaveLength(200);
    for (const f of facts.flatMap((c) => c.files)) expect(f).toMatch(/^[0-9a-f]{16}$/);
    expect(JSON.stringify(facts)).not.toContain("src/");
  });

  test("a commit is keyed by its sha's first 7 hex digits, lower-cased", () => {
    const facts = parseLog(rec(SHA1.toUpperCase(), 1, "me@x.test", "x\n"), { salt, email: "me@x.test", maxFiles: 200 });
    expect(facts[0]!.shaKey).toBe(keyedHash(salt, "abc1234"));
    expect(shaKey(salt, "ABC1234DEF")).toBe(keyedHash(salt, "abc1234"));
  });

  test("a record without a valid sha, time or field count is left out with its paths; a cut output loses its last record", () => {
    const out = rec(SHA1, 1, "me@x.test", "x\n") + "\0\x1enot-a-sha\x1f1\x1fme@x.test\x1fy\0\nbad.ts\0" + `\0\x1e${SHA3}\x1f\x1fme@x.test\x1fz\0`
      + `\0\x1e${SHA2}\x1f3\x1fme@x.test\0`;
    expect(logRecords(out).map((r) => [r.sha, r.files])).toEqual([[SHA1, []]]);
    const cut = rec(SHA1, 1, "me@x.test", "x\n", ["a.ts"]) + `\0\x1e${SHA2}\x1f2\x1fme@x.test\x1fpart`;
    expect(parseLog(cut, { salt, email: "me@x.test", maxFiles: 200, cut: true }).map((c) => c.files.length)).toEqual([1]);
  });
});

describe("one commit, one key: git and Claude Code agree (shared vector)", () => {
  let h: FakeHome;
  let restoreHome: () => void = () => {};
  beforeEach(() => { h = fakeHome(); restoreHome = isolateGitHome(path.join(h.root, "home")); });
  afterEach(() => { restoreHome(); h.cleanup(); });

  test("a git %H starting ABC1234 and a Claude Code sha ABC1234def both key as keyedHash(salt, \"abc1234\")", async () => {
    const want = keyedHash(salt, "abc1234");
    // the Claude Code side: a commit marker read from a transcript
    const t = new CcTranscript(ccSid("SV1")).prompt("commit it").tool("toolu_sv1", "Bash", { command: "git commit -m x" }, {
      content: "[main ABC1234] x", toolUseResult: { stdout: "", stderr: "", interrupted: false, gitOperation: { commit: { sha: "ABC1234def", kind: "commit", branch: "main" } } },
    });
    t.write(h, `.claude/projects/${slug("/work/p")}/${ccSid("SV1")}.jsonl`);
    const r = await scan({ env: h.env, plugins: [ccTranscripts], salt, repoSignals: false });
    const marker = r.store.all("marker").find((m) => m.kind === "commit");
    // the git side: the same commit in `git log` output, its sha in any case
    const [lower] = parseLog(rec("abc1234def5678901234567890abcdef12345678", 1, "me@x.test", "x\n"), { salt, email: "me@x.test", maxFiles: 200 });
    const [upper] = parseLog(rec("ABC1234DEF5678901234567890ABCDEF12345678", 1, "me@x.test", "x\n"), { salt, email: "me@x.test", maxFiles: 200 });
    expect([marker?.detail, lower!.shaKey, upper!.shaKey]).toEqual([want, want, want]);
  });
});
